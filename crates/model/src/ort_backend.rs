const SPEAKER_CONDITIONING_UNSUPPORTED: &str =
    "backend model does not support speaker conditioning";

/// ERB bands of the encoder input and of the ERB mask.
const NB_ERB: usize = 32;
/// Complex bins processed by deep filtering.
const NB_DF: usize = 96;
/// Deep filtering FIR order.
const DF_ORDER: usize = 5;
/// Values per hop in the `coefs` output: `NB_DF` bins x `DF_ORDER` taps x (re, im).
const DF_COEFS_LEN: usize = NB_DF * DF_ORDER * 2;
const EMB_DIM: i64 = 512;
const GRU_HIDDEN: i64 = 256;

/// File names of the three stateful graphs inside the model directory.
pub const ENC_FILE: &str = "enc.onnx";
pub const ERB_DEC_FILE: &str = "erb_dec.onnx";
pub const DF_DEC_FILE: &str = "df_dec.onnx";

/// Upper bound accepted for one graph file. The real graphs are 2-4 MB; anything far beyond
/// that is not one of ours and is refused before it is read into memory.
const MAX_GRAPH_BYTES: u64 = 64 * 1024 * 1024;

/// Expected SHA-256 (lowercase hex) of each stateful DeepFilterNet3 graph.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct StatefulDigests {
    pub enc: &'static str,
    pub erb_dec: &'static str,
    pub df_dec: &'static str,
}

