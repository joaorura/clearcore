#![allow(clippy::doc_markdown)]

//! ONNX Runtime (`ort`) streaming backend for the explicit-state DeepFilterNet3 graphs.
//!
//! Architecture mirrors [`crate::TractBackend`]'s role and `OpenVinoBackend`'s loading model:
//! the three stateful graphs (`enc.onnx`, `erb_dec.onnx`, `df_dec.onnx` — the ones in
//! `models/stateful/`) expose every recurrent state as a graph port, so the backend pins the
//! time axis to `S = 1` (one 10 ms hop) and feeds every `*_out` state back into the matching
//! `*_in` input after each hop. STFT, ERB feature extraction, mask/deep-filter application and
//! iSTFT stay in [`DspPipeline`]; this module is the neural half only.
//!
//! The approved release archive (`df-compatible-release-asset-v1`) contains the *segment*
//! graphs without state ports, which cannot stream frame-by-frame. The stateful graphs are
//! derived from it by `tools/accelerators/make_stateful_onnx.py` and are pinned here by
//! SHA-256 ([`APPROVED_STATEFUL_DIGESTS`], mirrored from `realtime-noise-accelerators` because
//! the two crates cannot depend on each other). Loading fails closed on any mismatch; the
//! verified bytes are the ones compiled (`commit_from_memory`, no re-read window).
//!
//! Voice profiles (`FiLM` speaker conditioning): the backend detects `gamma`/`beta` graph
//! inputs on both `enc` and `df_dec` at load time. The approved base graphs declare none, so
//! [`InferenceBackend::supports_voice_profile`] is `false` and a non-identity profile is
//! rejected explicitly (the policy of [`crate::reject_unsupported_voice_profile`]). A future
//! pDFNet3-style ONNX export with `FiLM` ports will light the hook up without API changes;
//! Tract keeps end-to-end `FiLM` coverage until such a fixture exists.

