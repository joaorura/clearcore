fn sha256_hex(bytes: &[u8]) -> String {
    use sha2::{Digest, Sha256};
    let digest = Sha256::digest(bytes);
    let mut hex = String::with_capacity(digest.len() * 2);
    for byte in digest {
        let _ = write!(hex, "{byte:02x}");
    }
    hex
}

fn read_verified_file(
    model_dir: &Path,
    file: &str,
    expected: &str,
) -> Result<Vec<u8>, InferenceError> {
    use std::io::Read as _;
    let path = model_dir.join(file);
    let read_error = InferenceError::Io;
    let mut bytes = Vec::new();
    std::fs::File::open(&path)
        .map_err(read_error)?
        .take(MAX_GRAPH_BYTES + 1)
        .read_to_end(&mut bytes)
        .map_err(read_error)?;
    if bytes.len() as u64 > MAX_GRAPH_BYTES {
        return Err(InferenceError::ModelCorruption(format!(
            "{} is larger than the {MAX_GRAPH_BYTES}-byte limit",
            path.display()
        )));
    }
    let actual = sha256_hex(&bytes);
    if actual.eq_ignore_ascii_case(expected) {
        Ok(bytes)
    } else {
        Err(InferenceError::AssetNotApproved(format!(
            "{file}: SHA-256 {actual} does not match the expected {expected}"
        )))
    }
}

/// The three stateful graphs as raw ONNX bytes: `(enc, erb_dec, df_dec)`.
type StatefulGraphs = (Vec<u8>, Vec<u8>, Vec<u8>);

/// Extracts the three stateful graphs from an in-memory `.tar.gz` archive. Members that are not
/// one of the three graph files (e.g. `config.ini`) are skipped; the three graphs must each be
/// present exactly once and within [`MAX_GRAPH_BYTES`]. The caller must have verified the archive
/// (e.g. [`crate::PdfNet3DevArchive::verify`] pins the whole-archive SHA-256); this helper does
/// not re-check digests.
fn extract_stateful_onnx(
    archive_bytes: &[u8],
) -> Result<StatefulGraphs, InferenceError> {
    use std::io::Read as _;
    let corruption = |reason: &str| InferenceError::ModelCorruption(reason.to_owned());
    let mut enc: Option<Vec<u8>> = None;
    let mut erb_dec: Option<Vec<u8>> = None;
    let mut df_dec: Option<Vec<u8>> = None;
    let mut archive = tar::Archive::new(flate2::read::GzDecoder::new(archive_bytes));
    let entries = archive.entries().map_err(|_| corruption("unreadable archive"))?;
    for entry in entries {
        let entry = entry.map_err(|_| corruption("unreadable archive"))?;
        let name = {
            let path = entry.path().map_err(|_| corruption("invalid member path"))?;
            path.file_name()
                .and_then(|n| n.to_str())
                .ok_or_else(|| corruption("non-UTF-8 member name"))?
                .to_owned()
        };
        let slot = match name.as_str() {
            ENC_FILE => &mut enc,
            ERB_DEC_FILE => &mut erb_dec,
            DF_DEC_FILE => &mut df_dec,
            _ => continue,
        };
        if slot.is_some() {
            return Err(corruption("duplicate graph member"));
        }
        let mut bytes = Vec::new();
        entry
            .take(MAX_GRAPH_BYTES + 1)
            .read_to_end(&mut bytes)
            .map_err(|_| corruption("unreadable graph member"))?;
        if bytes.len() as u64 > MAX_GRAPH_BYTES {
            return Err(corruption("graph member exceeds size limit"));
        }
        *slot = Some(bytes);
    }
    match (enc, erb_dec, df_dec) {
        (Some(e), Some(r), Some(d)) => Ok((e, r, d)),
        _ => Err(corruption("missing stateful graph member")),
    }
}

fn ort_error<R>(error: ort::Error<R>) -> InferenceError {
    InferenceError::InferenceExecution(error.to_string())
}

/// Compiles one graph from already-verified bytes. `Level3` + a small fixed thread pool keeps
/// the realtime budget (see the latency evidence in `docs/evidence/`).
fn load_session(graph: &[u8]) -> Result<Session, InferenceError> {
    let mut builder = Session::builder()
        .map_err(ort_error)?
        .with_optimization_level(GraphOptimizationLevel::Level3)
        .map_err(ort_error)?
        .with_intra_threads(2)
        .map_err(ort_error)?
        .with_inter_threads(1)
        .map_err(ort_error)?;
    builder.commit_from_memory(graph).map_err(ort_error)
}

fn zeros(shape: &[i64]) -> Result<Tensor<f32>, InferenceError> {
    let len = usize::try_from(shape.iter().product::<i64>())
        .map_err(|_| InferenceError::InputContract("invalid tensor shape".to_owned()))?;
    Tensor::from_array((shape.to_vec(), vec![0.0f32; len])).map_err(ort_error)
}

fn ones(shape: &[i64]) -> Result<Tensor<f32>, InferenceError> {
    let len = usize::try_from(shape.iter().product::<i64>())
        .map_err(|_| InferenceError::InputContract("invalid tensor shape".to_owned()))?;
    Tensor::from_array((shape.to_vec(), vec![1.0f32; len])).map_err(ort_error)
}

fn copy_into(dst: &mut Tensor<f32>, src: &[f32]) -> Result<(), InferenceError> {
    let (_, buf) = dst.try_extract_tensor_mut::<f32>().map_err(ort_error)?;
    if buf.len() != src.len() {
        return Err(InferenceError::InferenceExecution(format!(
            "tensor holds {} values, expected {}",
            buf.len(),
            src.len()
        )));
    }
    buf.copy_from_slice(src);
    Ok(())
}

fn zero_fill(tensor: &mut Tensor<f32>) -> Result<(), InferenceError> {
    let (_, buf) = tensor.try_extract_tensor_mut::<f32>().map_err(ort_error)?;
    buf.fill(0.0);
    Ok(())
}

fn extract_f32<'a>(
    outputs: &'a ort::session::SessionOutputs<'_>,
    name: &str,
) -> Result<&'a [f32], InferenceError> {
    let value = outputs
        .get(name)
        .ok_or_else(|| InferenceError::InferenceExecution(format!("missing output `{name}`")))?;
    let (_, data) = value.try_extract_tensor::<f32>().map_err(ort_error)?;
    Ok(data)
}

fn extract_scalar(outputs: &ort::session::SessionOutputs<'_>, name: &str) -> Result<f32, InferenceError> {
    let value = outputs
        .get(name)
        .ok_or_else(|| InferenceError::InferenceExecution(format!("missing output `{name}`")))?;
    value.try_extract_scalar::<f32>().map_err(ort_error)
}

fn sync_from_output(
    dst: &mut Tensor<f32>,
    outputs: &ort::session::SessionOutputs<'_>,
    name: &str,
) -> Result<(), InferenceError> {
    let src = extract_f32(outputs, name)?;
    copy_into(dst, src)
}

fn declares_film(session: &Session) -> bool {
    let mut gamma = false;
    let mut beta = false;
    for input in session.inputs() {
        match input.name() {
            "gamma" => gamma = true,
            "beta" => beta = true,
            _ => {}
        }
    }
    gamma && beta
}

/// `FiLM` conditioning tensors, present only when both `enc` and `df_dec` declare
/// `gamma`/`beta` inputs. The pDFNet3 Pro stateful graphs declare these ports with shape
/// `[1, S, FILM_HIDDEN_DIM]` (`S = 1` per streaming hop), i.e. **rank 3** — confirmed against
/// `APPROVED_PRO_STATEFUL_DIGESTS`. In identity mode `gamma = 1.0` (multiplicative) and
/// `beta = 0.0` (additive), so conditioning is a true pass-through; the approved base graphs
/// never reach this path.
struct FilmConditioning {
    enc_gamma: Tensor<f32>,
    enc_beta: Tensor<f32>,
    df_gamma: Tensor<f32>,
    df_beta: Tensor<f32>,
}

impl FilmConditioning {
    fn new() -> Result<Self, InferenceError> {
        let shape = [1, 1, FILM_HIDDEN_DIM as i64];
        Ok(Self {
            enc_gamma: ones(&shape)?,
            enc_beta: zeros(&shape)?,
            df_gamma: ones(&shape)?,
            df_beta: zeros(&shape)?,
        })
    }
}

/// The neural half of DeepFilterNet3 on ONNX Runtime: three streaming sessions with
/// explicit recurrent-state feedback at `S = 1`.
struct OrtSpectralModel {
    descriptor: BackendDescriptor,
    enc: Session,
    erb_dec: Session,
    df_dec: Session,
    // Feature inputs (rewritten every hop).
    feat_erb: Tensor<f32>,
    feat_spec: Tensor<f32>,
    // Encoder recurrent state and causal delay rings.
    enc_h: Tensor<f32>,
    enc_erb_buf: Tensor<f32>,
    enc_spec_buf: Tensor<f32>,
    // ERB decoder inputs and recurrent state.
    erb_emb: Tensor<f32>,
    erb_e0: Tensor<f32>,
    erb_e1: Tensor<f32>,
    erb_e2: Tensor<f32>,
    erb_e3: Tensor<f32>,
    erb_h: Tensor<f32>,
    // Deep-filter decoder inputs and recurrent state.
    df_emb: Tensor<f32>,
    df_c0: Tensor<f32>,
    df_h: Tensor<f32>,
    df_c0_buf: Tensor<f32>,
    /// `Some` only when the graphs declare `FiLM` ports.
    film: Option<FilmConditioning>,
    frames: u64,
}

impl OrtSpectralModel {
    fn new(
        enc_graph: &[u8],
        erb_graph: &[u8],
        df_graph: &[u8],
        descriptor: BackendDescriptor,
    ) -> Result<Self, InferenceError> {
        let enc = load_session(enc_graph)?;
        let erb_dec = load_session(erb_graph)?;
        let df_dec = load_session(df_graph)?;
        let film = if declares_film(&enc) && declares_film(&df_dec) {
            Some(FilmConditioning::new()?)
        } else {
            None
        };
        Ok(Self {
            descriptor,
            feat_erb: zeros(&[1, 1, 1, NB_ERB as i64])?,
            feat_spec: zeros(&[1, 2, 1, NB_DF as i64])?,
            enc_h: zeros(&[1, 1, GRU_HIDDEN])?,
            enc_erb_buf: zeros(&[1, 1, 2, NB_ERB as i64])?,
            enc_spec_buf: zeros(&[1, 2, 2, NB_DF as i64])?,
            erb_emb: zeros(&[1, 1, EMB_DIM])?,
            erb_e0: zeros(&[1, 64, 1, 32])?,
            erb_e1: zeros(&[1, 64, 1, 16])?,
            erb_e2: zeros(&[1, 64, 1, 8])?,
            erb_e3: zeros(&[1, 64, 1, 8])?,
            erb_h: zeros(&[2, 1, GRU_HIDDEN])?,
            df_emb: zeros(&[1, 1, EMB_DIM])?,
            df_c0: zeros(&[1, 64, 1, NB_DF as i64])?,
            df_h: zeros(&[2, 1, GRU_HIDDEN])?,
            df_c0_buf: zeros(&[1, 64, 4, NB_DF as i64])?,
            enc,
            erb_dec,
            df_dec,
            film,
            frames: 0,
        })
    }

    fn set_film(&mut self, vectors: &FiLMVectors) -> Result<(), InferenceError> {
        match &mut self.film {
            Some(film) => {
                copy_into(&mut film.enc_gamma, &vectors.gamma_enc)?;
                copy_into(&mut film.enc_beta, &vectors.beta_enc)?;
                copy_into(&mut film.df_gamma, &vectors.gamma_df)?;
                copy_into(&mut film.df_beta, &vectors.beta_df)?;
                Ok(())
            }
            None => Err(InferenceError::InputContract(
                SPEAKER_CONDITIONING_UNSUPPORTED.to_owned(),
            )),
        }
    }
}

impl SpectralModelBackend for OrtSpectralModel {
    fn descriptor(&self) -> BackendDescriptor {
        self.descriptor.clone()
    }

    /// Runs one 10 ms hop through the encoder and both decoders, then advances every state.
    ///
    /// `feat_spec` is `[real; 96]` followed by `[imag; 96]`. State is committed only after all
    /// three stages succeeded; on error the caller should [`Self::reset`] before reusing the
    /// session, because the decoders may have run with a half-updated hop.
    fn process_spectrum(
        &mut self,
        features: &ExtractedFeatures,
    ) -> Result<ModelFrameOutput, InferenceError> {
        if features
            .feat_erb
            .iter()
            .chain(features.feat_spec.iter().flatten())
            .any(|value| !value.is_finite())
        {
            return Err(InferenceError::InputContract(
                "feature frame contains a non-finite value".to_owned(),
            ));
        }
        copy_into(&mut self.feat_erb, &features.feat_erb)?;
        let mut spec = [0.0f32; 2 * NB_DF];
        spec[..NB_DF].copy_from_slice(&features.feat_spec[0]);
        spec[NB_DF..].copy_from_slice(&features.feat_spec[1]);
        copy_into(&mut self.feat_spec, &spec)?;

        // Encoder.
        let mut enc_inputs: Vec<(&str, &Tensor<f32>)> = vec![
            ("feat_erb", &self.feat_erb),
            ("feat_spec", &self.feat_spec),
            ("h_in", &self.enc_h),
            ("feat_erb_buf", &self.enc_erb_buf),
            ("feat_spec_buf", &self.enc_spec_buf),
        ];
        if let Some(film) = &self.film {
            enc_inputs.push(("gamma", &film.enc_gamma));
            enc_inputs.push(("beta", &film.enc_beta));
        }
        let enc_out = self.enc.run(enc_inputs).map_err(ort_error)?;
        let lsnr = extract_scalar(&enc_out, "lsnr")?;
        sync_from_output(&mut self.erb_e0, &enc_out, "e0")?;
        sync_from_output(&mut self.erb_e1, &enc_out, "e1")?;
        sync_from_output(&mut self.erb_e2, &enc_out, "e2")?;
        sync_from_output(&mut self.erb_e3, &enc_out, "e3")?;
        sync_from_output(&mut self.erb_emb, &enc_out, "emb")?;
        sync_from_output(&mut self.df_emb, &enc_out, "emb")?;
        sync_from_output(&mut self.df_c0, &enc_out, "c0")?;
        sync_from_output(&mut self.enc_h, &enc_out, "h_out")?;
        sync_from_output(&mut self.enc_erb_buf, &enc_out, "feat_erb_buf_out")?;
        sync_from_output(&mut self.enc_spec_buf, &enc_out, "feat_spec_buf_out")?;
        let e0 = extract_f32(&enc_out, "e0")?.to_vec();
        let e1 = extract_f32(&enc_out, "e1")?.to_vec();
        let e2 = extract_f32(&enc_out, "e2")?.to_vec();
        let e3 = extract_f32(&enc_out, "e3")?.to_vec();
        let emb = extract_f32(&enc_out, "emb")?.to_vec();
        let c0 = extract_f32(&enc_out, "c0")?.to_vec();
        drop(enc_out);

        // ERB decoder.
        copy_into(&mut self.erb_e0, &e0)?;
        copy_into(&mut self.erb_e1, &e1)?;
        copy_into(&mut self.erb_e2, &e2)?;
        copy_into(&mut self.erb_e3, &e3)?;
        copy_into(&mut self.erb_emb, &emb)?;
        let erb_inputs: Vec<(&str, &Tensor<f32>)> = vec![
            ("emb", &self.erb_emb),
            ("e3", &self.erb_e3),
            ("e2", &self.erb_e2),
            ("e1", &self.erb_e1),
            ("e0", &self.erb_e0),
            ("h_in", &self.erb_h),
        ];
        if let Some(film) = &self.film {
            let _ = film;
        }
        let erb_out = self.erb_dec.run(erb_inputs).map_err(ort_error)?;
        let mask = extract_f32(&erb_out, "m")?;
        if mask.len() != NB_ERB {
            return Err(InferenceError::InferenceExecution(format!(
                "unexpected ERB mask size {} (want {NB_ERB})",
                mask.len()
            )));
        }
        if !lsnr.is_finite() || mask.iter().any(|value| !value.is_finite()) {
            return Err(InferenceError::NonFiniteOutput);
        }
        let mut erb_gains = [0.0f32; NB_ERB];
        erb_gains.copy_from_slice(mask);
        sync_from_output(&mut self.erb_h, &erb_out, "h_out")?;
        drop(erb_out);

        // Deep-filter decoder.
        copy_into(&mut self.df_emb, &emb)?;
        copy_into(&mut self.df_c0, &c0)?;
        let mut df_inputs: Vec<(&str, &Tensor<f32>)> = vec![
            ("emb", &self.df_emb),
            ("c0", &self.df_c0),
            ("h_in", &self.df_h),
            ("c0_buf", &self.df_c0_buf),
        ];
        if let Some(film) = &self.film {
            df_inputs.push(("gamma", &film.df_gamma));
            df_inputs.push(("beta", &film.df_beta));
        }
        let df_out = self.df_dec.run(df_inputs).map_err(ort_error)?;
        let coefs = extract_f32(&df_out, "coefs")?;
        if coefs.len() != DF_COEFS_LEN {
            return Err(InferenceError::InferenceExecution(format!(
                "unexpected deep-filter coefs size {} (want {DF_COEFS_LEN})",
                coefs.len()
            )));
        }
        if coefs.iter().any(|value| !value.is_finite()) {
            return Err(InferenceError::NonFiniteOutput);
        }
        let df_coefs: Vec<[Complex32; DF_ORDER]> = coefs
            .chunks_exact(DF_COEFS_LEN / NB_DF)
            .map(|bin| {
                std::array::from_fn(|tap| Complex32::new(bin[2 * tap], bin[2 * tap + 1]))
            })
            .collect();
        sync_from_output(&mut self.df_h, &df_out, "h_out")?;
        sync_from_output(&mut self.df_c0_buf, &df_out, "c0_buf_out")?;
        self.frames = self.frames.saturating_add(1);

        Ok(ModelFrameOutput {
            lsnr,
            erb_gains: Some(erb_gains),
            df_coefs: Some(df_coefs),
        })
    }

    /// Zeroes every recurrent state (GRU hidden states and causal delay rings).
    fn reset(&mut self) -> Result<(), InferenceError> {
        for tensor in [
            &mut self.enc_h,
            &mut self.enc_erb_buf,
            &mut self.enc_spec_buf,
            &mut self.erb_h,
            &mut self.df_h,
            &mut self.df_c0_buf,
        ] {
            zero_fill(tensor)?;
        }
        self.frames = 0;
        Ok(())
    }
}

/// ONNX Runtime backend for the explicit-state DeepFilterNet3 graphs (one hop per frame).
///
/// Drop-in replacement for [`crate::TractBackend`]: same [`DspPipeline`], same
/// [`InferenceBackend`] contract, same algorithmic latency.
pub struct OrtBackend {
    descriptor: BackendDescriptor,
    pipeline: DspPipeline,
    model: OrtSpectralModel,
    film_supported: bool,
    active_profile: Option<VoiceProfile>,
}

impl std::fmt::Debug for OrtBackend {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("OrtBackend")
            .field("descriptor", &self.descriptor)
            .field("film_supported", &self.film_supported)
            .field("active_profile", &self.active_profile)
            .finish_non_exhaustive()
    }
}

impl OrtBackend {
    /// Loads the three stateful graphs from `model_dir` after verifying each against
    /// [`APPROVED_STATEFUL_DIGESTS`], and builds the shared DSP pipeline around them.
    ///
    /// `asset_id`/`asset_sha256` are provenance recorded in the [`BackendDescriptor`]; the
    /// per-graph digests are the security boundary. `cpu_profile` is the project-wide CPU
    /// gate (same policy as [`crate::TractBackend`]), not an ONNX Runtime requirement.
    pub fn new(
        model_dir: impl AsRef<Path>,
        asset_id: impl Into<String>,
        asset_sha256: impl Into<String>,
        cpu_profile: CpuProfile,
    ) -> Result<Self, InferenceError> {
        Self::new_with_digests(
            model_dir,
            asset_id,
            asset_sha256,
            cpu_profile,
            APPROVED_STATEFUL_DIGESTS,
        )
    }

    /// Like [`Self::new`], but verifies each graph against `digests` instead of
    /// [`APPROVED_STATEFUL_DIGESTS`]. Use this to load an alternate pinned set (e.g.
    /// [`APPROVED_PRO_STATEFUL_DIGESTS`] for a directory of Pro graphs).
    pub fn new_with_digests(
        model_dir: impl AsRef<Path>,
        asset_id: impl Into<String>,
        asset_sha256: impl Into<String>,
        cpu_profile: CpuProfile,
        digests: StatefulDigests,
    ) -> Result<Self, InferenceError> {
        cpu_profile.ensure_supported()?;
        let model_dir = model_dir.as_ref();
        let enc = read_verified_file(model_dir, ENC_FILE, digests.enc)?;
        let erb_dec = read_verified_file(model_dir, ERB_DEC_FILE, digests.erb_dec)?;
        let df_dec = read_verified_file(model_dir, DF_DEC_FILE, digests.df_dec)?;
        let descriptor = BackendDescriptor {
            backend: "ort",
            backend_version: "deep_filter-v0.5.6",
            runtime: "onnxruntime",
            runtime_version: "2.0.0-rc.13",
            asset_id: asset_id.into(),
            asset_sha256: asset_sha256.into(),
            cpu_profile: cpu_profile.name(),
        };
        Self::from_graphs(&enc, &erb_dec, &df_dec, descriptor)
    }

    /// Builds the backend from three already-extracted, already-verified stateful graphs.
    fn from_graphs(
        enc_graph: &[u8],
        erb_graph: &[u8],
        df_graph: &[u8],
        descriptor: BackendDescriptor,
    ) -> Result<Self, InferenceError> {
        let model = OrtSpectralModel::new(enc_graph, erb_graph, df_graph, descriptor.clone())?;
        let film_supported = model.film.is_some();
        Ok(Self {
            descriptor,
            pipeline: DspPipeline::new(DspPipelineConfig::default())?,
            model,
            film_supported,
            active_profile: None,
        })
    }

    /// Loads the backend from an in-memory `.tar.gz` archive containing the three stateful
    /// graphs (`enc.onnx`, `erb_dec.onnx`, `df_dec.onnx`; other members such as `config.ini` are
    /// ignored). The caller must have verified the archive (e.g. [`crate::PdfNet3DevArchive`]
    /// pins the whole-archive SHA-256 before decompression); this constructor does not re-check
    /// digests. `descriptor` records provenance (backend/runtime/asset id/hash/cpu profile).
    pub fn from_archive_bytes(
        archive_bytes: &[u8],
        descriptor: BackendDescriptor,
    ) -> Result<Self, InferenceError> {
        let (enc, erb_dec, df_dec) = extract_stateful_onnx(archive_bytes)?;
        Self::from_graphs(&enc, &erb_dec, &df_dec, descriptor)
    }

    /// Whether the loaded graphs declare `gamma`/`beta` `FiLM` inputs (pDFNet3-style models).
    #[must_use]
    pub const fn supports_speaker_conditioning(&self) -> bool {
        self.film_supported
    }

    #[must_use]
    pub const fn active_voice_profile(&self) -> Option<&VoiceProfile> {
        self.active_profile.as_ref()
    }

    /// Zeroes the DSP pipeline memories and every recurrent model state.
    pub fn reset(&mut self) -> Result<(), InferenceError> {
        self.pipeline.reset();
        self.model.reset()
    }

    /// Activates `profile` (or removes conditioning with `None`) between two frames.
    ///
    /// Everything is validated before anything is applied: on error the previous profile stays
    /// active. The recurrent state (GRUs, delay rings) is preserved, so there is no
    /// re-warm-up. A profile that is not the identity needs graphs with `FiLM` inputs; a
    /// neutral profile is accepted by every model.
    pub fn set_voice_profile(
        &mut self,
        profile: Option<&VoiceProfile>,
    ) -> Result<(), InferenceError> {
        let film = match profile {
            Some(profile) => {
                profile.verify_integrity()?;
                Some(&profile.film)
            }
            None => None,
        };
        match film {
            _ if !self.film_supported => {
                if film.is_some_and(|vectors| !vectors.is_identity()) {
                    return Err(InferenceError::InputContract(
                        SPEAKER_CONDITIONING_UNSUPPORTED.to_owned(),
                    ));
                }
            }
            Some(vectors) => self.model.set_film(vectors)?,
            None => self.model.set_film(&FiLMVectors::identity())?,
        }
        self.active_profile = profile.cloned();
        Ok(())
    }
}

impl InferenceBackend for OrtBackend {
    fn descriptor(&self) -> BackendDescriptor {
        self.descriptor.clone()
    }

    fn process(&mut self, input: &AudioFrame) -> Result<ProcessedFrame, InferenceError> {
        if input.iter().any(|sample| !sample.is_finite()) {
            return Err(InferenceError::InputContract(
                "input frame contains a non-finite sample".to_owned(),
            ));
        }
        let samples = self.pipeline.process_frame(input, &mut self.model)?;
        ProcessedFrame::checked(samples, ALGORITHM_LATENCY_SAMPLES, self.descriptor())
    }

    fn algorithmic_latency_samples(&self) -> u32 {
        ALGORITHM_LATENCY_SAMPLES
    }

    fn set_voice_profile(&mut self, profile: Option<&VoiceProfile>) -> Result<(), InferenceError> {
        Self::set_voice_profile(self, profile)
    }

    /// Only graphs with `FiLM` inputs can apply a profile built by enrollment.
    fn supports_voice_profile(&self) -> bool {
        self.film_supported
    }
}
